export type MessageKey = keyof typeof spanish;
export type Messages = Record<MessageKey, string>;
export const english = Object.fromEntries(Object.keys(spanish).map(key => [key, key])) as Messages;
export const locales = {
  en: { name: "English", messages: english, assistanceLanguage: "English" },
  es: { name: "Español", messages: spanish satisfies Messages, assistanceLanguage: "Spanish" },
} as const;
export type Locale = keyof typeof locales;
export const LOCALE_STORAGE_KEY = "career-assistant:locale";
export function isLocale(value: string | null): value is Locale { return value !== null && Object.hasOwn(locales, value); }
export function translate(locale: Locale, message: string, values: Record<string, string | number> = {}): string {
  const oversized = message.match(/^(.*): keep the value within 4,000 characters\.$/);
  if (oversized) { message = "{name}: keep the value within 4,000 characters."; values = { ...values, name: oversized[1] }; }
  const translated = (locales[locale].messages as Record<string, string>)[message] ?? message;
  return translated.replace(/\{(\w+)\}/g, (token, key: string) => String(values[key] ?? token));
}
