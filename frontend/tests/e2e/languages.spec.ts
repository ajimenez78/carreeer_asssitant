import { expect, test, type Page } from "@playwright/test";
import { LOCALE_STORAGE_KEY } from "../../src/lib/i18n/catalogs";
import { MOCK_FAILURE_KEY, MOCK_STORAGE_KEY } from "../../src/lib/mock-transport";

const switchTo = (page: Page, locale: string) => page.locator(".locale-switcher select").selectOption(locale);
const nav = (page: Page, name: RegExp) => page.locator(".sidebar nav").getByRole("button", { name }).click();

test("English and Spanish switch immediately, persist, and preserve the full editing flow", async ({ page }, info) => {
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
  await page.goto("/");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await switchTo(page, "es");
  await expect(page.locator("html")).toHaveAttribute("lang", "es");
  await expect(page).toHaveTitle("Tu trabajo ideal | Asistente profesional");
  await expect(page.getByRole("main").getByRole("alert")).toContainText("Introduce una descripción");
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("Define tu trabajo ideal.");
  const description = "Busco un puesto Staff de arquitectura y trabajo remoto cerca de Madrid.";
  await page.getByLabel("Descripción de tu trabajo ideal").fill(description);
  await switchTo(page, "en");
  await expect(page.getByLabel("Your ideal job description")).toHaveValue(description);
  await switchTo(page, "es");
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Borrador guardado");
  await nav(page, /Trayectoria/);
  await page.getByLabel("Tipo de fuente").selectOption("text");
  await page.getByLabel("Nombre de la fuente").fill("Save draft");
  await page.getByLabel("Texto de trayectoria").fill("Experiencia previa en sistemas distribuidos.");
  await page.getByRole("button", { name: "Añadir fuente", exact: true }).click();
  await page.getByLabel("Datos revisados, uno por línea").fill("Save draft");
  await switchTo(page, "en");
  await expect(page.getByLabel("Reviewed facts, one per line")).toHaveValue("Save draft");
  await expect(page.getByRole("button", { name: "Review Save draft", exact: true })).toBeVisible();
  await switchTo(page, "es");
  await page.getByRole("button", { name: "Aceptar los datos revisados" }).click();
  await nav(page, /Aclara/);
  await expect(page.getByLabel("Idioma de la asistencia")).toHaveValue("Spanish");
  await page.evaluate(key => sessionStorage.setItem(key, "ai"), MOCK_FAILURE_KEY);
  await page.getByRole("button", { name: "Solicitar preguntas y sugerencias" }).click();
  await expect(page.getByRole("main").getByRole("alert")).toContainText("El asistente no está disponible");
  await switchTo(page, "en");
  await expect(page.getByRole("main").getByRole("alert")).toContainText("The assistant is unavailable");
  await switchTo(page, "es");
  await page.getByRole("button", { name: "Solicitar preguntas y sugerencias" }).click();
  const question = page.locator(".question-card").first();
  await expect(question).toContainText("rango salarial");
  await question.getByRole("textbox").fill("Una respuesta todavía sin guardar.");
  await switchTo(page, "en");
  await expect(question.getByRole("textbox")).toHaveValue("Una respuesta todavía sin guardar.");
  await expect(question).toContainText("rango salarial");
  await switchTo(page, "es");
  await nav(page, /Revisa y guarda/);
  const salary = page.locator(".criterion").filter({ has: page.locator('input[value="salary"]') });
  await expect(salary.getByLabel("Tipo de valor")).toHaveValue("unknown");
  await salary.getByLabel("Tipo de valor").selectOption("compensation");
  await salary.getByLabel("Mínimo", { exact: true }).fill("100000");
  await expect(salary.getByLabel("Periodo de pago").getByRole("option", { name: "Por año" })).toHaveAttribute("value", "year");
  await expect(salary.getByLabel("Base fiscal").getByRole("option", { name: "Bruto" })).toHaveAttribute("value", "gross");
  await switchTo(page, "en");
  await expect(salary.getByLabel("Minimum", { exact: true })).toHaveValue("100000");
  await switchTo(page, "es");
  await page.getByRole("button", { name: "Aplicar las sugerencias revisadas y guardar" }).click();
  await expect(page.getByRole("status")).toContainText("Borrador guardado");
  await page.screenshot({ path: info.outputPath("spanish-review.png"), fullPage: true });
  const before = await page.evaluate(key => localStorage.getItem(key), MOCK_STORAGE_KEY);
  await switchTo(page, "en");
  expect(await page.evaluate(key => localStorage.getItem(key), MOCK_STORAGE_KEY)).toBe(before);
  await switchTo(page, "es");
  await page.reload();
  await expect(page.getByLabel("Descripción de tu trabajo ideal")).toHaveValue(description);
  await expect(page.locator(".locale-switcher select")).toHaveValue("es");
  await nav(page, /Revisa y guarda/);
  await expect(salary.getByLabel("Mínimo", { exact: true })).toHaveValue("100000");
  await page.getByText("Eliminar esta definición", { exact: true }).click();
  await page.getByRole("button", { name: "Eliminar la definición y sus fuentes", exact: true }).click();
  await expect(page.getByText("¿Eliminar todo el trabajo actual? Esta acción no se puede deshacer.")).toBeVisible();
  await page.getByRole("button", { name: "Cancelar la eliminación", exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test("Spanish source errors and pending source input survive a language switch", async ({ page }) => {
  await page.goto("/"); await switchTo(page, "es");
  await page.getByLabel("Descripción de tu trabajo ideal").fill("Un puesto con conciliación");
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await nav(page, /Trayectoria/);
  await page.getByLabel("Tipo de fuente").selectOption("url");
  await page.getByLabel("Nombre de la fuente").fill("Perfil");
  await page.getByLabel("URL pública").fill("https://www.linkedin.com/in/example");
  await page.getByRole("button", { name: "Añadir fuente", exact: true }).click();
  await expect(page.getByText("Extracción fallida", { exact: true })).toBeVisible();
  await expect(page.getByText("No se ha podido obtener esta página. Sube un documento o pega su texto.")).toBeVisible();
  await page.getByLabel("Tipo de fuente").selectOption("text");
  await page.getByLabel("Nombre de la fuente").fill("Notas sin guardar");
  await page.getByLabel("Texto de trayectoria").fill("My English notes stay exactly as typed.");
  await switchTo(page, "en");
  await expect(page.getByLabel("Source name")).toHaveValue("Notas sin guardar");
  await expect(page.getByLabel("Background text")).toHaveValue("My English notes stay exactly as typed.");
  await switchTo(page, "es");
  await expect(page.getByLabel("Texto de trayectoria")).toHaveValue("My English notes stay exactly as typed.");
});

test("invalid stored locales fall back to English and switching works without storage", async ({ page }) => {
  await page.addInitScript(key => {
    localStorage.setItem(key, "unsupported");
    const original = Storage.prototype.setItem;
    Storage.prototype.setItem = function (k, value) { if (k === key) throw new DOMException("Storage unavailable"); original.call(this, k, value); };
  }, LOCALE_STORAGE_KEY);
  await page.goto("/"); await expect(page.getByRole("heading", { level: 1 })).toHaveText("Define your ideal job.");
  await page.locator(".locale-switcher select").focus(); await page.keyboard.press("ArrowDown"); await page.keyboard.press("Enter");
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("Define tu trabajo ideal.");
  await expect(page.locator("html")).toHaveAttribute("lang", "es");
});
